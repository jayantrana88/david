"""Regenerate src/sourcing/geo-data.ts from pycountry (the countries and subdivisions the Python gazetteer,
stages/sourcing/linkedin/geo.py, indexes). Run with the daemon's venv from the repo root:

    venv/Scripts/python cloudflare/scripts/make_geo_data.py

Cities are not bundled: the Worker looks them up through Open-Meteo's geocoding API (GeoNames data, the same
source as geonamescache) and caches each answer in D1.
"""
import re
import sys
import unicodedata
from pathlib import Path

import pycountry

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from stages.sourcing.linkedin.geo import EUROPE, NORTH_AMERICA  # noqa: E402


def norm(s: str) -> str:
    s = unicodedata.normalize("NFKD", s or "")
    s = "".join(ch for ch in s if not unicodedata.combining(ch))
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9]+", " ", s.lower())).strip()


countries: dict[str, str] = {}
for c in pycountry.countries:
    for attr in ("name", "official_name", "common_name"):
        v = getattr(c, attr, None)
        if v:
            countries.setdefault(norm(v), c.alpha_2)

iso = sorted(c.alpha_2 for c in pycountry.countries)
subdivs: dict[str, tuple[str, str]] = {}
priority = sorted(NORTH_AMERICA) + sorted(EUROPE)
for cc in priority + sorted(set(iso) - set(priority)):
    for s in pycountry.subdivisions.get(country_code=cc) or []:
        subdivs.setdefault(norm(s.name), (cc, s.code.split("-", 1)[1]))

out = Path(__file__).resolve().parents[1] / "src" / "sourcing" / "geo-data.ts"
lines = [
    "// Generated by scripts/make_geo_data.py from pycountry: do not edit by hand.",
    "// COUNTRIES: \"<normalized name>|<ISO alpha-2>\" lines. SUBDIVISIONS: \"<normalized name>|<country>|<code>\" lines,",
    "// in the Python gazetteer's priority order (the first entry for a name wins).",
    f"export const ISO_CODES = {' '.join(iso)!r};",
    "export const COUNTRIES = `" + "\n".join(f"{n}|{cc}" for n, cc in countries.items()) + "`;",
    "export const SUBDIVISIONS = `" + "\n".join(f"{n}|{cc}|{code}" for n, (cc, code) in subdivs.items()) + "`;",
    "",
]
out.write_text("\n".join(lines).replace("ISO_CODES = '", 'ISO_CODES = "').replace("';\nexport const COUNTRIES", '";\nexport const COUNTRIES'), encoding="utf-8")
print(f"{out}: {len(countries)} country names, {len(subdivs)} subdivisions, {out.stat().st_size // 1024} KB")
